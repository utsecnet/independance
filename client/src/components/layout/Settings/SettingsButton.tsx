interface SettingsButtonProps {
  active: boolean;
  onToggle: () => void;
}

// Bottom-left, right beside React Flow's own zoom/fit-view controls (which
// occupy that corner by default) — grouping it with the map's other
// persistent controls reads as "another map control" rather than a
// disconnected button, and keeps it out of the way of the create/placement
// controls already anchored top-left.
export function SettingsButton({ active, onToggle }: SettingsButtonProps) {
  return (
    <button
      type="button"
      className={`${styles.button} ${active ? styles.active : ""}`}
      onClick={onToggle}
      aria-pressed={active}
      aria-label="Settings"
      title="Settings"
    >
      <SettingsIcon />
    </button>
  );
}
